    expect(meeting.timelineDisplay).toEqual({ projectIds: [], taskIds: [] });
    expect(meeting.participants.map((person) => person.personId)).toEqual([viewer.person.id]);
    expect(meeting.rangeStart.toISOString()).toBe("2026-09-01T01:00:00.000Z");
