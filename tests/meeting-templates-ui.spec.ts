    await expect(end).toHaveValue("2026-09-08T10:00");
    await page.getByRole("button", { name: "关闭模板提示", exact: true }).click();
    await expect(page.getByLabel("会议主题", { exact: true })).toHaveValue("空值替换");
    await deleteMeetingTemplate(actor(admin), { templateId: empty.id, expectedVersion: empty.version });
    await page.getByLabel("会议主题", { exact: true }).fill(`独立会议 ${name}`);
    await page.getByLabel("会议纪要", { exact: true }).fill("会议自定义纪要");
    await expectHealthyPage(page);
    await page.getByRole("button", { name: "创建会议记录", exact: true }).click();
