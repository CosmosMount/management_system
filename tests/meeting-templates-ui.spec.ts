    await start.fill("2026-09-01T09:00");
    await end.fill("2026-09-08T10:00");
    await page.getByRole("button", { name: "预览工作时间线", exact: true }).click();
    await expect(page.getByTestId("meeting-timeline")).toBeVisible();
    const empty = await createMeetingTemplate(actor(admin), { requestId: randomUUID(), name: `空内容模板 ${randomUUID()}`, topic: "空值替换", personIds: [viewer.person.id], minutes: "", timelineDisplay: { projectIds: [], taskIds: [] } });
    await page.getByRole("button", { name: "更换模板", exact: true }).click();
